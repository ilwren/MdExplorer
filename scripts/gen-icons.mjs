// Generates src/ui/icons.tsx from @material-design-icons/svg (round style).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'node_modules', '@material-design-icons', 'svg', 'round');

const wanted = [
  // navigation / shell
  'home', 'menu', 'layers', 'search', 'more_vert', 'settings', 'close', 'check',
  'arrow_back', 'arrow_forward', 'arrow_upward', 'refresh', 'chevron_right', 'chevron_left',
  'expand_more', 'keyboard_return', 'filter_none',
  // destinations
  'star', 'star_border', 'schedule', 'image', 'movie', 'description', 'folder', 'folder_open',
  'delete', 'delete_forever', 'restore', 'delete_sweep', 'photo_library', 'video_library',
  'audiotrack', 'storage', 'sd_storage', 'download', 'category',
  // actions
  'add', 'note_add', 'create_new_folder', 'content_cut', 'content_copy', 'content_paste',
  'drive_file_rename_outline', 'edit_note', 'sort', 'swap_vert', 'grid_view', 'view_list',
  'view_headline', 'visibility', 'share', 'open_in_new', 'select_all', 'filter_list',
  'content_paste_search', 'tune', 'push_pin', 'info', 'folder_zip', 'archive',
  // preview / facts
  'aspect_ratio', 'save', 'schedule', 'straighten', 'code', 'picture_as_pdf', 'audio_file',
  'videocam', 'insert_drive_file', 'description', 'lock', 'public', 'inventory_2',
  'speed', 'data_usage', 'light_mode', 'dark_mode', 'brightness_6', 'motion_photos_off',
  'animation', 'sort_by_alpha', 'arrow_downward', 'arrow_drop_down', 'check_circle',
  'radio_button_unchecked', 'error_outline', 'block', 'folder_shared', 'logout',
  'preview', 'zoom_in', 'zoom_out', 'fit_screen', 'edit', 'mic', 'graphic_eq',
  'my_location', 'cancel', 'folder_zip', 'unarchive', 'create_new_folder', 'device_hub', 'fact_check',
  'manage_search', 'filter_alt', 'swap_horiz', 'view_column', 'volume_up', 'policy', 'update', 'toc', 'vertical_split',
];

const aliases = {
  files: 'description',
  recent: 'schedule',
  video: 'movie',
  audio: 'audiotrack',
  docs: 'description',
  batch_rename: 'edit_note',
  view_grid: 'grid_view',
  view_list: 'view_headline',
  open_with: 'open_in_new',
};

const icons = {};
const missing = [];
for (const name of [...new Set(wanted)]) {
  const p = join(srcDir, `${name}.svg`);
  if (!existsSync(p)) { missing.push(name); continue; }
  const svg = readFileSync(p, 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  icons[name] = inner;
}

const lines = [];
lines.push('// AUTO-GENERATED by scripts/gen-icons.mjs — do not edit.');
lines.push('/* eslint-disable */');
lines.push('import React from "react";');
lines.push('');
lines.push('export const ICONS: Record<string, string> = {');
for (const [k, v] of Object.entries(icons)) lines.push(`  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
lines.push('};');
lines.push('');
for (const [k, v] of Object.entries(aliases)) {
  lines.push(`ICONS[${JSON.stringify(k)}] = ICONS[${JSON.stringify(v)}];`);
}
lines.push('');
lines.push(`export type IconName = keyof typeof ICONS | string;`);
lines.push('');
lines.push(`export function Icon(props: { name: IconName; size?: number; className?: string; style?: React.CSSProperties; weight?: number }) {`);
lines.push(`  const { name, size = 24, className, style, weight } = props;`);
lines.push(`  const inner = ICONS[name] ?? ICONS.insert_drive_file;`);
lines.push(`  return (`);
lines.push(`    <svg`);
lines.push(`      className={className}`);
lines.push(`      style={{ width: size, height: size, display: "block", fontWeight: weight, ...style }}`);
lines.push(`      viewBox="0 0 24 24"`);
lines.push(`      fill="currentColor"`);
lines.push(`      aria-hidden="true"`);
lines.push(`      dangerouslySetInnerHTML={{ __html: inner }}`);
lines.push(`    />`);
lines.push(`  );`);
lines.push(`}`);
lines.push('');

mkdirSync(join(root, 'src', 'ui'), { recursive: true });
writeFileSync(join(root, 'src', 'ui', 'icons.tsx'), lines.join('\n'));
console.log(`icons generated: ${Object.keys(icons).length}`, missing.length ? `MISSING: ${missing.join(', ')}` : '');
